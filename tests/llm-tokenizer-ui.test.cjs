test('presets reconstruct exact UTF-8, word pieces split, repeated entries keep IDs, changes update immediately',async()=>{
  const {dom,get,w}=fixture();const real=vendor.create();
  for(const option of get('Preset').options){
    get('Preset').value=option.value;get('Preset').dispatchEvent(new w.Event('change'));
    await flush();assert.equal(get('Results').hidden,false);assert.equal(get('Inspection'),null);
    const result=engine.analyze(option.value,real);
    assert.deepEqual([...get('Pairs').querySelectorAll('.tokenizer-id')].map(b=>Number(b.textContent)),result.tokens.map(t=>t.id));
    assert.equal(new TextDecoder().decode(new Uint8Array(result.tokens.flatMap(t=>t.bytes))),option.value);
  }
  assert.ok(engine.analyze('unbelievable',real).tokens.length>1);
  const repeats=engine.analyze('Pizza, pizza, pizza!',real).tokens.filter(t=>t.text===' pizza');
  assert.equal(repeats.length,2);assert.equal(repeats[0].id,repeats[1].id);
  assert.ok(engine.analyze(get('Input').value,real).tokens.some(t=>t.text===null));
  assert.match(get('Pairs').textContent,/bytes/);
  dom.window.close();
});
