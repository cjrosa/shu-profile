const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require('../tools/llm-tokenizer/node_modules/jsdom');

test('window examination detects both directions, ignores equality, and freezes playback',()=>{
  const html=fs.readFileSync('cs339/tcp_full_V3.html','utf8');
  const dom=new JSDOM(html,{runScripts:'outside-only'}),w=dom.window;
  w.HTMLElement.prototype.scrollIntoView=()=>{};
  w.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
  w.HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new w.Event('close'));};
  w.HTMLCanvasElement.prototype.getContext=()=>new Proxy({}, {get:(_,k)=>k==='createLinearGradient'?()=>({addColorStop(){}}):()=>{},set:()=>true});
  w.requestAnimationFrame=()=>{};
  const script=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)][0][1];
  w.eval(script.replace('requestAnimationFrame(loop);\nrenderLog();',`window.windowAPI={loop,manual:(rw,cw,flight)=>{mode='manual';st='established';snd.rw=rw;cc.cwnd=cw;snd.inflight=flight;segSize=1000;upd();return canSend();},clock:()=>protocolTime,change:(rw,cw)=>{st='established';mode='sim';snd.rw=rw;cc.cwnd=cw;segSize=1000;upd();}};requestAnimationFrame(loop);\nrenderLog();`));
  const api=w.windowAPI,dialog=w.document.getElementById('window-examine-dialog');
  const toggle=w.document.getElementById('window-examine-mode');toggle.checked=true;toggle.dispatchEvent(new w.Event('change'));
  api.change(9000,2);assert.equal(dialog.open,false);
  api.change(2000,2);assert.equal(dialog.open,false);
  api.change(1000,2);assert.equal(dialog.open,true);
  const graph=w.document.getElementById('window-history-graph');
  assert.equal(graph.querySelectorAll('path').length,2);
  assert.match(graph.getAttribute('aria-label'),/rwnd 1000 bytes, cwnd 2000 bytes/);
  assert.match(graph.querySelector('path').getAttribute('d'),/ H /);
  assert.match(w.document.getElementById('window-examine-title').textContent,/cwnd to rwnd/);
  const before=api.clock();api.loop(100);api.loop(200);assert.equal(api.clock(),before);
  w.document.getElementById('window-examine-continue').click();
  api.change(9000,2);assert.equal(dialog.open,true);
  assert.match(w.document.getElementById('window-examine-title').textContent,/rwnd to cwnd/);
  w.document.getElementById('window-examine-pause').click();assert.equal(dialog.open,false);
  api.loop(300);assert.equal(api.clock(),before);
  assert.equal(api.manual(10000,2,2000),false,'manual cannot exceed cwnd');
  assert.equal(api.manual(1000,5,1000),false,'manual cannot exceed rwnd');
  assert.equal(api.manual(10000,2,1000),true,'manual can fill remaining effective window');
  assert.match(w.document.getElementById('window-values').textContent,/min\(rwnd 10000 B, cwnd 2000 B\) = 2000 B/);
  assert.equal(w.document.querySelector('#window-values .is-limiting').textContent,'cwnd 2000 B');
  assert.equal(w.document.getElementById('window-cwnd-row').hidden,false);
  toggle.checked=false;toggle.dispatchEvent(new w.Event('change'));
  const marker=w.document.getElementById('window-cwnd-marker');
  api.manual(10000,7,7000);
  const position=marker.style.cssText;
  api.manual(8000,7,6000);
  assert.equal(marker.style.cssText,position,'unchanged cwnd stays fixed as rwnd and in-flight bytes change');
  assert.equal(marker.textContent,'cwnd 7000 B');
  api.manual(8000,7,12000);
  const expanded=marker.style.cssText;
  assert.match(w.document.getElementById('window-excess-label').textContent,/5000 B/);
  api.manual(10000,7,0);
  assert.equal(marker.style.cssText,expanded,'scale does not shrink as outstanding bytes are acknowledged');
  assert.equal(w.document.getElementById('window-scale-max').textContent,'12000 B (100% of scale)');
  dom.window.close();
});
